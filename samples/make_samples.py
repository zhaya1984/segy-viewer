def main():
    for name, cfg in SAMPLES.items():
        if 'grid' in cfg:
            x, y, il, xl = grid_from_origin(epsg=cfg['epsg'], **cfg['grid'])
            path = write_segy(SAMPLES_DIR / name, cfg['ebcdic'], x, y,
                              n_samples=cfg['n_samples'], ilines=il, xlines=xl)
        else:
            x, y = line_from_lonlat(*cfg['line'], epsg=cfg['epsg'], n=300)
            path = write_segy(SAMPLES_DIR / name, cfg['ebcdic'], x, y)
        print(f'{path.name}: {path.stat().st_size / 1024:.0f} KB')


if __name__ == '__main__':
    main()
