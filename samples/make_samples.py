"""
make_samples.py - Generate small synthetic SEG-Y files for demos and tests.

    python samples/make_samples.py

The files are clearly labelled SYNTHETIC in their EBCDIC header. Trace data is
random reflectivity convolved with a Ricker wavelet, which is only there so the
file looks like seismic. The viewer reads headers only.
"""
from pathlib import Path

import numpy as np
import segyio
from pyproj import Transformer

SAMPLES_DIR = Path(__file__).resolve().parent
N_SAMPLES = 250
SAMPLE_INTERVAL_US = 4000


def ricker(freq_hz: float, dt_s: float, length_s: float = 0.128) -> np.ndarray:
    t = np.arange(-length_s / 2, length_s / 2, dt_s)
    a = (np.pi * freq_hz * t) ** 2
    return (1 - 2 * a) * np.exp(-a)


def synthetic_traces(n_traces: int, n_samples: int, seed: int = 0) -> np.ndarray:
    """Laterally continuous random reflectivity convolved with a 25 Hz Ricker wavelet."""
    rng = np.random.default_rng(seed)
    reflectivity = rng.normal(0, 1, n_samples) * (rng.random(n_samples) > 0.9)
    wavelet = ricker(25, SAMPLE_INTERVAL_US / 1e6)
    traces = np.empty((n_traces, n_samples), dtype=np.float32)
    for i in range(n_traces):
        shifted = np.roll(reflectivity, int(3 * np.sin(i / 40)))
        traces[i] = np.convolve(shifted, wavelet, mode='same') + rng.normal(0, 0.02, n_samples)
    return traces


def write_segy(path: Path, ebcdic: str, x: np.ndarray, y: np.ndarray,
               scalar: int = -100, coord_units: int = 1,
               n_samples: int = N_SAMPLES,
               ilines: np.ndarray = None, xlines: np.ndarray = None) -> Path:
    """
    Write a post-stack SEG-Y with CDP and source coordinates.
    Pass ilines / xlines (bytes 189 / 193) to write a 3D volume.
    A negative scalar stores coordinates as integers × abs(scalar) (e.g. centimetres).
    """
    def stored(v):
        return int(round(v * abs(scalar))) if scalar < 0 else int(round(v / max(scalar, 1)))

    spec = segyio.spec()
    spec.format = 5  # IEEE float
    spec.samples = range(n_samples)
    spec.tracecount = len(x)

    traces = synthetic_traces(len(x), n_samples)
    with segyio.create(str(path), spec) as f:
        f.text[0] = segyio.tools.create_text_header(
            {i + 1: line for i, line in enumerate(ebcdic.strip().splitlines()[:40])})
        f.bin.update(hdt=SAMPLE_INTERVAL_US, hns=n_samples, format=5)
        for i in range(len(x)):
            f.header[i] = {
                segyio.TraceField.TRACE_SEQUENCE_FILE: i + 1,
                segyio.TraceField.CDP: 1000 + i,
                segyio.TraceField.CDP_X: stored(x[i]),
                segyio.TraceField.CDP_Y: stored(y[i]),
                segyio.TraceField.SourceX: stored(x[i]),
                segyio.TraceField.SourceY: stored(y[i]),
                segyio.TraceField.SourceGroupScalar: scalar,
                segyio.TraceField.CoordinateUnits: coord_units,
                segyio.TraceField.offset: 0,
                segyio.TraceField.TraceIdentificationCode: 1,
            }
            if ilines is not None:
                f.header[i].update({
                    segyio.TraceField.INLINE_3D: int(ilines[i]),
                    segyio.TraceField.CROSSLINE_3D: int(xlines[i]),
                })
            f.trace[i] = traces[i]
    return path


def line_from_lonlat(start, end, epsg: int, n: int):
    """Straight line between two WGS84 lon/lat points, returned in the target projected CRS."""
    to_proj = Transformer.from_crs(4326, epsg, always_xy=True)
    x0, y0 = to_proj.transform(*start)
    x1, y1 = to_proj.transform(*end)
    return np.linspace(x0, x1, n), np.linspace(y0, y1, n)


def grid_from_origin(origin, epsg: int, n_il: int, n_xl: int, il_first: int, xl_first: int,
                     line_step: int, bin_m: float, azimuth_deg: float):
    """
    Rotated 3D bin grid. Inlines run along `azimuth_deg` (clockwise from grid north),
    crosslines at right angles. Every `line_step`-th inline/crossline is kept.
    Returns x, y, ilines, xlines with crosslines varying fastest.
    """
    x0, y0 = Transformer.from_crs(4326, epsg, always_xy=True).transform(*origin)
    az = np.radians(azimuth_deg)
    along = np.array([np.sin(az), np.cos(az)])            # inline direction
    across = np.array([np.cos(az), -np.sin(az)])          # crossline direction

    il_idx, xl_idx = np.meshgrid(np.arange(n_il), np.arange(n_xl), indexing='ij')
    il_idx, xl_idx = il_idx.ravel(), xl_idx.ravel()
    step_m = line_step * bin_m
    x = x0 + xl_idx * step_m * along[0] + il_idx * step_m * across[0]
    y = y0 + xl_idx * step_m * along[1] + il_idx * step_m * across[1]
    return x, y, il_first + il_idx * line_step, xl_first + xl_idx * line_step


